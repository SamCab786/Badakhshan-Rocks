export const CATALOG_MAP = new Map<string, MineralSpecimen>(
  GEOLOGY_CATALOG.map((item) => [item.id, item])
);

export function normalizeSearch(str: string): string {
  return String(str || '')
    .toLowerCase()
    .normalize('NFKC')
    .replace(/[^a-z0-9\u0600-\u06ff]+/g, ' ')
    .trim();
}

/**
 * Searches and finds an authoritative catalog match by English name, Persian name, or ID
 */
export function findCatalogMatch(
  nameEn: string,
  nameFa?: string
): MineralSpecimen | null {
  const normEn = normalizeSearch(nameEn);
  const normFa = nameFa ? normalizeSearch(nameFa) : '';

  // 1. Direct ID match
  if (CATALOG_MAP.has(nameEn.toLowerCase())) {
    return CATALOG_MAP.get(nameEn.toLowerCase())!;
  }

  // 2. Exact name matching
  for (const item of GEOLOGY_CATALOG) {
    if (
      normalizeSearch(item.name_en) === normEn ||
      (normFa && normalizeSearch(item.name_fa) === normFa) ||
      normalizeSearch(item.id) === normEn
    ) {
      return item;
    }
  }

  // 3. Substring matching
  for (const item of GEOLOGY_CATALOG) {
    const itemNormEn = normalizeSearch(item.name_en);
    const itemNormFa = normalizeSearch(item.name_fa);
    if (
      normEn.length >= 3 &&
      (itemNormEn.includes(normEn) || normEn.includes(itemNormEn))
    ) {
      return item;
    }
    if (
      normFa.length >= 3 &&
      (itemNormFa.includes(normFa) || normFa.includes(itemNormFa))
    ) {
      return item;
    }
  }

  return null;
}
